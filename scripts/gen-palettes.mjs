// Generates src/palettes.generated.ts from the [data-palette="x"] blocks in
// theme.css, so the CSS stays the single source of palette ids and labels.
//
//   node scripts/gen-palettes.mjs          write the file
//   node scripts/gen-palettes.mjs --check  exit 1 if the file is stale

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = join(packageRoot, "theme.css");
const outputPath = join(packageRoot, "src", "palettes.generated.ts");

const COMMENT = /\/\*[\s\S]*?\*\//g;
// A selector and its body, with no braces inside — so for a rule nested in
// @media or @layer, this matches the inner rule alone.
const RULE = /([^{}]+)\{([^{}]*)\}/g;
const PALETTE_SELECTOR = /\[data-palette=["']?([\w-]+)["']?\]/g;
const LABEL = /--palette-label\s*:\s*(["'])(.*?)\1/;

function fail(message) {
  console.error(`gen-palettes: ${message}`);
  process.exit(1);
}

function readPalettes(css) {
  const found = new Map();
  const uncommented = css.replace(COMMENT, "");

  for (const [, selector, body] of uncommented.matchAll(RULE)) {
    const targetsRoot = selector.includes(":root");
    const labelMatch = body.match(LABEL);

    for (const [, id] of selector.matchAll(PALETTE_SELECTOR)) {
      const existing = found.get(id);
      if (existing === undefined) {
        found.set(id, {
          id,
          label: labelMatch ? labelMatch[2] : id,
          isDefault: targetsRoot,
        });
      } else if (targetsRoot) {
        existing.isDefault = true;
      }
    }
  }

  return Array.from(found.values());
}

function render(palettes) {
  const rows = palettes.map(
    (palette) =>
      `  { id: ${JSON.stringify(palette.id)}, ` +
      `label: ${JSON.stringify(palette.label)}, ` +
      `isDefault: ${palette.isDefault} },`
  );
  return [
    "// Generated by scripts/gen-palettes.mjs from theme.css — do not edit.",
    "// Run `npm run gen:palettes` after changing a [data-palette] block.",
    "",
    "export const PALETTES = [",
    ...rows,
    "] as const;",
    "",
  ].join("\n");
}

function normalizeLineEndings(text) {
  return text.replace(/\r\n/g, "\n");
}

const palettes = readPalettes(readFileSync(cssPath, "utf8"));

if (palettes.length === 0) {
  fail('no [data-palette="x"] rules found in theme.css');
}
const defaults = palettes.filter((palette) => palette.isDefault);
if (defaults.length !== 1) {
  fail(
    `expected exactly one palette whose rule also targets :root, ` +
      `found ${defaults.length}`
  );
}

const output = render(palettes);

if (process.argv.includes("--check")) {
  const current = existsSync(outputPath)
    ? normalizeLineEndings(readFileSync(outputPath, "utf8"))
    : "";
  if (current !== output) {
    fail("src/palettes.generated.ts is stale — run `npm run gen:palettes`");
  }
  console.log("gen-palettes: up to date");
} else {
  writeFileSync(outputPath, output);
  console.log(`gen-palettes: wrote ${palettes.length} palettes`);
}
